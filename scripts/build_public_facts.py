"""Build data/public_facts.json — the single source of truth for every number
SwarmLabs publishes on a public page.

Why this exists
---------------
An external reviewer (2026-09-18) reported our engine count as "143" on one page
and "155" on another. Neither number is generated by anything: the machine truth
is 62 validated scenarios backed by 54 engine modules. The 143 was hand-typed
marketing copy that had drifted from the artifacts.

The rule this script enforces is the same one the V&V package follows:
**a published number must be derivable from an artifact, or it must not be
published at all.** Anything we cannot derive is registered here explicitly as
`undefined` — with the reason — so that `check_public_numbers.py` fails on it
instead of letting it pass silently.

Two counts that are BOTH real and must not be conflated
-------------------------------------------------------
* `validated_scenarios` (62)  — scenarios that have a published 10-chapter V&V
  report in frontend_fixed/reports/. This is the number to publish.
* `defined_scenarios` (72)    — scenarios whose code exists in the registries
  but which do NOT yet have a published report. Do not publish this as "how many
  we have validated"; it overstates by 10.
* `pending_engines_total`     — engines declared as backlog in
  engine.domains.PENDING_CATEGORIES. These are UNBUILT. A page may cite a
  per-domain figure here, but it must say "pending" next to the number.

Stdlib only. Deterministic: same inputs -> byte-identical output (except the
generated_at_utc stamp).
"""
from __future__ import annotations

import hashlib
import json
import os
import random
import re
from datetime import datetime, timezone
from pathlib import Path

# ---- L-10 可复现性（2026-10-17 查缺补漏） ----
# 主流程固定随机种子。虽然本脚本目前以纯确定性 IO 为主，但一旦引入任何
# 采样/打乱/近似算法（例如按域抽样出统计），未固定 seed 会让 public_facts.json
# 每次运行产生字节不同的产物，让「95 场景主干结果可复现」的对外承诺失效。
# 统一 seed = 42（与 engine.baybe_adapter / engine.calibration_rl 内部约定一致）。
BUILD_SEED = 42


def _fix_seeds() -> int:
    """固定所有可用 PRNG。返回使用的 seed 值，供 metadata 记录。"""
    random.seed(BUILD_SEED)
    try:
        import numpy as np  # noqa: F401
        np.random.seed(BUILD_SEED)
    except Exception:
        pass  # numpy 缺失时不影响（本脚本 stdlib 路径不依赖 numpy）
    try:
        import torch
        torch.manual_seed(BUILD_SEED)
    except Exception:
        pass
    return BUILD_SEED


ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "public_facts.json"

REPORTS_INDEX = ROOT / "frontend_fixed" / "reports" / "index.json"
GATE_LEDGER = ROOT / "frontend_fixed" / "reports" / "gate_ledger.json"
HELDOUT = ROOT / "frontend_fixed" / "reports" / "heldout_index.json"
ANCHORS = ROOT / "frontend_fixed" / "reports" / "wet_lab_anchors.json"
DENSITY = ROOT / "frontend_fixed" / "reports" / "scenario_library_density.json"
TRUST = ROOT / "data" / "trust_surface.json"
ENTITY_STORE = ROOT / "data" / "entity_store.json"
ENGINE_DIR = ROOT / "engine"
GEN_BENCH = ROOT / "data" / "generalization_bench.json"
G3_ALIGNED = ROOT / "data" / "g3_aligned_benchmark.json"

# 领域归一：trust_surface.json 的 domain 是自由文本且中英混排，
# 按「/」或「 / 」之前的首段归类，再把中文标签映射到英文键。
DOMAIN_ALIASES = {"微生物": "Microorganisms"}


def _load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def _sha12(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:12]


def _domain_bucket(label: str) -> str:
    head = re.split(r"\s*/\s*", (label or "").strip(), maxsplit=1)[0].strip()
    return DOMAIN_ALIASES.get(head, head)


def collect() -> dict:
    facts: dict[str, dict] = {}
    sources: dict[str, str] = {}

    def add(key, value, unit, source, note=""):
        facts[key] = {"value": value, "unit": unit, "source": source, "note": note}

    # ---- scenario / verdict counts: frontend_fixed/reports/index.json ----
    idx = _load(REPORTS_INDEX)
    sources["reports_index"] = {
        "path": "frontend_fixed/reports/index.json",
        "sha256_12": _sha12(REPORTS_INDEX),
        "generated_at_utc": idx.get("generated_at_utc"),
    }
    add("validated_scenarios", idx["total"], "scenarios",
        "frontend_fixed/reports/index.json#total",
        "报告库中已生成 10 章 V&V 报告的场景总数——对外只能引用这个数")
    c = idx["counts"]
    add("verdict_pass", c["PASS"], "scenarios", "frontend_fixed/reports/index.json#counts.PASS")
    add("verdict_marginal", c["MARGINAL"], "scenarios", "frontend_fixed/reports/index.json#counts.MARGINAL")
    add("verdict_refuted", c["REFUTED"], "scenarios", "frontend_fixed/reports/index.json#counts.REFUTED")
    add("verdict_error", c["ERROR"], "scenarios", "frontend_fixed/reports/index.json#counts.ERROR")

    # ---- gate ledger must agree with the report index ----
    led = _load(GATE_LEDGER)
    sources["gate_ledger"] = {
        "path": "frontend_fixed/reports/gate_ledger.json",
        "sha256_12": _sha12(GATE_LEDGER),
        "generated_at_utc": led.get("generated_at_utc"),
    }
    if led["counts"] != c:
        raise SystemExit(
            f"FATAL: gate_ledger.counts {led['counts']} != index.counts {c} — "
            "两个产物口径已经分裂，先修产物再生成事实表"
        )

    # ---- domain split: data/trust_surface.json ----
    tr = _load(TRUST)
    sources["trust_surface"] = {
        "path": "data/trust_surface.json",
        "sha256_12": _sha12(TRUST),
        "generated_at": tr.get("generated_at"),
    }
    ov = tr["overall"]
    scope = ov.get("coverage_scope", {})
    add("cross_domain_scenarios", scope.get("cross_domain"), "scenarios",
        "data/trust_surface.json#overall.coverage_scope.cross_domain")
    add("microbio_scenarios", scope.get("microbio_registered"), "scenarios",
        "data/trust_surface.json#overall.coverage_scope.microbio_registered",
        "仅在页面上同时出现「microbial / 微生物」字样时才可引用此子集口径")
    add("rubric_full_pass", ov.get("rubric_full_pass"), "scenarios",
        "data/trust_surface.json#overall.rubric_full_pass",
        "七项 rubric 全通过数（注意：≠ verdict PASS 数）")

    # ---- per-domain validated counts (mechanical: first segment of domain) ----
    per_domain: dict[str, int] = {}
    for r in tr.get("rows", []):
        b = _domain_bucket(r.get("domain", ""))
        per_domain[b] = per_domain.get(b, 0) + 1
    add("validated_scenarios_by_domain", per_domain, "scenarios per domain",
        "histogram_alias(data/trust_surface.json#rows[].domain, "
        + json.dumps(DOMAIN_ALIASES, ensure_ascii=False) + ")",
        "按 domain 首段机械归类（别名表就写在 source 里，校验器按同一张表重算），"
        "用于博客/行业页按领域引用；求和应等于 validated_scenarios。"
        "此前 source 只写 `rows[].domain`（聚合语义、无法求值）⇒ 这条事实永远不参与"
        "陈旧性检查，正是 57→64 那类盲区")

    # ---- store points actually used for calibration ----
    npts = sum(int(r.get("n_store") or 0) for r in tr.get("rows", []))
    add("store_points_total", npts, "points",
        "sum(data/trust_surface.json#rows[].n_store)",
        "全部场景的校准用存储点数合计——这是唯一可辩护的「数据量」口径，"
        "远低于任何「百万级验证数据点」的说法")

    # ---- held-out stress suites: these are where real REFUTED live ----
    ho = _load(HELDOUT)
    sources["heldout_index"] = {
        "path": "frontend_fixed/reports/heldout_index.json",
        "sha256_12": _sha12(HELDOUT),
        "generated_at_utc": None,
    }
    rh = ho["robustness_heldout"]["counts"]
    ex = ho["extrapolation_stress"]["counts"]
    add("heldout_robustness_refuted", rh["REFUTED"], "scenarios",
        "frontend_fixed/reports/heldout_index.json#robustness_heldout.counts.REFUTED",
        "鲁棒性留出集下被判 REFUTED 的场景数")
    add("extrapolation_stress_refuted", ex["REFUTED"], "scenarios",
        "frontend_fixed/reports/heldout_index.json#extrapolation_stress.counts.REFUTED",
        "外推压力测试下被判 REFUTED 的场景数——「诚实失败」的真正证据在这里，"
        "不在 62 场景的主账本里（后者为 0）")

    # ---- wet-lab anchors ----
    an = _load(ANCHORS)
    sources["wet_lab_anchors"] = {
        "path": "frontend_fixed/reports/wet_lab_anchors.json",
        "sha256_12": _sha12(ANCHORS),
        "generated_at_utc": an.get("generated_at_utc"),
    }
    add("wet_lab_anchors", len(an["anchors"]), "anchors",
        "count(frontend_fixed/reports/wet_lab_anchors.json#anchors)",
        "有物理对应物、可对照文献区间的锚点；UNANCHORED 非失败（见该文件 note）。"
        "来源写成 count(...)：裸指针指向数组时无法与标量比较，会被静默跳过")

    # ---- experimental ground truth: 主动披露项，expected 0 ----
    # `evidence_type` / `overall.honesty` 由 scripts/patch_trust_surface_honesty.py
    # 写入。trust_surface.json 一旦被 paper_validation_loop 重新生成，这块元数据会
    # **静默丢失**（2026-09-21 12:30 实测发生），事实表随之退化成读一个不存在的
    # 字段——值恒为 0，永远无法陈旧。所以这里 fail-closed：补丁缺失就直接报错。
    hon = (tr.get("overall") or {}).get("honesty")
    if not hon:
        raise SystemExit(
            "FATAL: data/trust_surface.json 缺 overall.honesty —— 先跑 "
            "scripts/patch_trust_surface_honesty.py。该补丁是 evidence_type / "
            "experimental_ground_truth_count 的唯一写入方，不跑它事实表只能编一个 0")
    ev = sorted({r.get("evidence_type") for r in tr.get("rows", [])
                 if r.get("evidence_type")})
    add("experimental_ground_truth", hon.get("experimental_ground_truth_count"),
        "scenarios",
        "data/trust_surface.json#overall.honesty.experimental_ground_truth_count",
        f"evidence_type 取值集合 = {ev}；0 = 尚无湿实验真值，"
        "这与门禁中「pre-revenue / bus factor=1」并列，属主动披露项。"
        "来源必须指向 honesty 块（脚本写入的真值），不能指向 rows[].evidence_type"
        "——补丁缺失时那个投影会 KeyError，值也就永远算不出来")

    # ---- engine modules: the ONLY defensible denominator for "engine" ----
    # 真源：scripts/engine_module_count.py（唯一实现，与 build_frontend_metrics 共用）
    import sys as _sys
    _scripts_dir = str(Path(__file__).resolve().parent)
    if _scripts_dir not in _sys.path:
        _sys.path.insert(0, _scripts_dir)
    from engine_module_count import engine_module_count as _engine_module_count  # noqa: E402
    mods_n = _engine_module_count(ENGINE_DIR)
    add("engine_modules", mods_n, "modules",
        "count(engine/*.py excluding __init__.py)",
        "engine/ 下的 Python 模块数。若对外要用「引擎」一词，只能写「engine modules」"
        "并说明它计数的是模块而非已验证场景。"
        "来源写成 count(...) 而非裸 glob：裸 glob 会被口径门禁整条跳过，"
        "于是这条事实**永远不参与陈旧性检查**（2026-09-21 实测：引擎 57→64，"
        "事实表与前端 5 处仍写 57，门禁却报 0 违规）。"
        "**L-01 修复（2026-10-17）**：真源统一到 scripts/engine_module_count.py，"
        "排除 __init__.py，与 build_frontend_metrics.ENGINE_MODULES 严格一致。")

    # ---- scenario_library_density.json: defined vs pending ----
    dn = _load(DENSITY)
    sources["scenario_density"] = {
        "path": "frontend_fixed/reports/scenario_library_density.json",
        "sha256_12": _sha12(DENSITY),
        "generated_at": dn.get("generated_at"),
    }
    add("defined_scenarios", dn.get("total_scenarios_loaded"), "scenarios",
        "frontend_fixed/reports/scenario_library_density.json#total_scenarios_loaded",
        "代码注册表里存在但**尚未发布 V&V 报告**的场景总数。对外不可当作"
        "「已验证场景数」引用——会多算若干个")
    pend = dn.get("pending_categories") or {}
    pend_flat = {k: (v.get("count") if isinstance(v, dict) else v) for k, v in pend.items()}
    add("pending_engines_by_domain", pend_flat, "engines per domain",
        "frontend_fixed/reports/scenario_library_density.json#pending_categories",
        "engine.domains.PENDING_CATEGORIES 的积压项。这些引擎**尚未实现**；"
        "引用时必须紧邻「pending / 计划中」字样")
    add("pending_engines_total", sum(v for v in pend_flat.values() if isinstance(v, int)),
        "engines", "sum(frontend_fixed/reports/scenario_library_density.json#pending_categories)",
        "待实现引擎总数。引用时必须写 pending，且不得与 engine_modules 相加")
    ds = dn.get("density_summary") or {}
    add("pending_engines_gap", ds.get("total_gap_pending_engines"), "engines",
        "frontend_fixed/reports/scenario_library_density.json#density_summary.total_gap_pending_engines",
        "只统计「零已验证场景」类目里的待实现引擎——小于 pending_engines_total，"
        "因为后者还包含已有验证场景的类目（如 Chemistry 11）。引用时须说明是 gap 口径")

    # ---- structured research entity store ----
    es = _load(ENTITY_STORE)
    sources["entity_store"] = {
        "path": "data/entity_store.json",
        "sha256_12": _sha12(ENTITY_STORE),
        "built_at": (es.get("meta") or {}).get("built_at"),
    }
    ec = es.get("counts") or {}
    add("knowledge_graph_entities", ec.get("TOTAL_ENTITIES"), "entities",
        "data/entity_store.json#counts.TOTAL_ENTITIES",
        "结构化科研实体库总量（works/authors/institutions/concepts/venues/references/"
        "trends/research_gaps/cross_domain_bridges/coauthor_insights）。"
        "这是知识图谱规模，**不是**验证数据点，不得写成 validation data points")
    add("knowledge_graph_works", ec.get("works"), "works",
        "data/entity_store.json#counts.works")
    add("knowledge_graph_references", ec.get("references"), "references",
        "data/entity_store.json#counts.references")

    # ---- generalization bench: G1/G2/G3 通过率（诚实信号，2026-10-08 补）----
    # 报告特别强调 G3=0 是「跨学科泛化不成立」的核心证据；把它加入 facts 后，
    # 若未来有人偷偷把 0 改成非 0（或反过来让整体被截断），
    # 下面的漂移门禁会立刻报错——避免「诚实信号被静默粉饰」。
    if GEN_BENCH.exists():
        gb = _load(GEN_BENCH)
        sources["generalization_bench"] = {
            "path": "data/generalization_bench.json",
            "sha256_12": _sha12(GEN_BENCH),
            "generated_at": gb.get("generated_at"),
        }
        gb_overall = gb.get("overall") or {}
        add("generalization_g1_pass", gb_overall.get("g1"),
            "fraction (pass / (pass+fail, na 除外))",
            "data/generalization_bench.json#overall.g1",
            "G1 参数外推通过率。当前实测 0.0——不是数字好看的问题，"
            "而是「当前架构只支持设计域内插值验证」的诚实声明。")
        add("generalization_g2_pass", gb_overall.get("g2"),
            "fraction",
            "data/generalization_bench.json#overall.g2",
            "G2 留一维通过率。当前实测 0.0。")
        add("generalization_g3_pass", gb_overall.get("g3"),
            "fraction",
            "data/generalization_bench.json#overall.g3",
            "G3 留一学科通过率。当前实测 0.0——跨学科外推在 GP 方法下不可达，"
            "是 A15 硬约束的直接量化证据。任何非 0 的对外声称都需要新证据支撑。")
        add("generalization_g3_na", gb_overall.get("g3_na"),
            "scenarios (na)",
            "data/generalization_bench.json#overall.g3_na",
            "G3 中 na（不适用）的场景数。na 不算失败也不算通过。")
    else:
        # 事实表必须显式标注缺失而不是静默跳过
        add("generalization_g3_pass", None, "UNSOURCED",
            None, "data/generalization_bench.json 不存在——门禁会因此失败")

    # ---- terms we CANNOT source: registered so the gate fails on them ----
    undefined = {
        "engines": {
            "reason": "没有任何产物生成「已交付引擎数量」。index/lab/login/pricing/terms 五处"
                      "手写的 143（以及外部评审读到的 155）均无来源。"
                      "合法替代：engine_modules（模块数）、validated_scenarios（已验证场景数）、"
                      "pending_engines_total（待实现数，须标 pending）。",
            "page_hits_2026_09_20": [
                "frontend_fixed/index.html", "frontend_fixed/lab.html",
                "frontend_fixed/login.html", "frontend_fixed/pricing.html",
                "frontend_fixed/terms.html",
            ],
        },
        "validation_data_points": {
            "reason": "index.html / login.html 宣称 900k+ validation data points，无产物支撑；"
                      "可辩护的同类量是 store_points_total 与 knowledge_graph_entities，"
                      "且两者语义不同（校准用点数 vs 知识图谱实体），不得互换。",
            "page_hits_2026_09_20": [
                "frontend_fixed/index.html", "frontend_fixed/login.html",
            ],
        },
    }
    for k, v in undefined.items():
        facts[k] = {"value": None, "unit": "UNSOURCED", "source": None,
                    "note": v["reason"]}

    return {
        "name": "SwarmLabs public facts — 公开页数字的单一真源",
        "generated_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "sources": sources,
        "facts": facts,
        "undefined_claims": undefined,
    }


def main() -> None:
    seed = _fix_seeds()
    d = collect()
    d["build"] = {"script": "scripts/build_public_facts.py", "seed": seed}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    n = len(d["facts"])
    un = len(d["undefined_claims"])
    print(f"wrote {OUT.relative_to(ROOT)}  ({n} facts, {un} registered-as-unsourced, seed={seed})")


if __name__ == "__main__":
    main()

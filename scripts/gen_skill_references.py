#!/usr/bin/env python3
"""Generate the microbiology scenario reference doc for the Agent Skill.

Reads data/microbiology_scenarios.json (exported from engine/microbiology_full.py)
and writes the references/microbiology-scenarios.md consumed by
skills/agent-skills/virtual-experiment-design/SKILL.md.

Re-run after scenario changes:
    python scripts/gen_skill_references.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "microbiology_scenarios.json")
DST = os.path.join(
    ROOT, "skills", "agent-skills", "virtual-experiment-design",
    "references", "microbiology-scenarios.md",
)
API_SCENARIOS = 11  # cross-domain benchmarks currently live on v3


def main() -> None:
    with open(SRC, encoding="utf-8") as fh:
        data = json.load(fh)
    sc = data["scenarios"]

    dims: dict[int, int] = {}
    for s in sc:
        dims[s["dim"]] = dims.get(s["dim"], 0) + 1
    dist = " / ".join(f"{n} x {d}D" for d, n in sorted(dims.items()))

    L = [
        "# Microbiology Scenario Catalog (%d)" % len(sc),
        "",
        "> Auto-generated by `scripts/gen_skill_references.py` from",
        "> `data/microbiology_scenarios.json` (source: `engine/microbiology_full.py`).",
        ">",
        "> All %d scenarios are live and samplable via `POST /api/v3/sample`." % len(sc),
        "> The v3 API serves %d scenarios in total: these %d microbiology ones plus" % (len(sc) + API_SCENARIOS, len(sc)),
        "> %d cross-domain benchmarks. Verified 2026-09-10 by sampling a spread of" % API_SCENARIOS,
        "> keys across the list; every one returned points.",
        ">",
        "> Bounds and published parameters below are the authoritative values for",
        "> offline design work and for reproducing the server's numbers locally.",
        "",
        "Dimensions: %s" % dist,
        "",
        "## Overview",
        "",
        "| # | key | domain | dim | bounds |",
        "|---|-----|--------|-----|--------|",
    ]
    for i, s in enumerate(sc, 1):
        bounds = ", ".join("[%s, %s]" % (lo, hi) for lo, hi in s["bounds"])
        domain = s.get("domain", "").replace("|", "/")
        L.append("| %d | `%s` | %s | %s | %s |" % (i, s["key"], domain, s["dim"], bounds))

    L += ["", "## Published parameters and references", ""]
    for s in sc:
        L += ["### `%s`" % s["key"], ""]
        if s.get("published"):
            L += ["**Published params:** %s" % s["published"], ""]
        if s.get("references"):
            L += ["**References:**", ""]
            L += ["- %s" % r for r in s["references"]]
            L.append("")
        L += [
            "_GP settings: length-scale=%s, noise=%s_" % (s.get("ls"), s.get("noise")),
            "",
        ]

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("WROTE %s (%d lines, %d scenarios)" % (DST, len(L), len(sc)))


if __name__ == "__main__":
    main()
